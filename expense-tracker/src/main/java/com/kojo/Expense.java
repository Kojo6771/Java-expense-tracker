package com.kojo;

public class Expense {
    private double amount;
    private Date date;
    private String category;
    private String name;
    private int id;

    public Expense(double amount, Date date, String category, String name, int id){
        this.amount = amount;
        this.date = date;
        this.category = category;
        this.name = name;
        this.id = id;
        
    }


    
}
